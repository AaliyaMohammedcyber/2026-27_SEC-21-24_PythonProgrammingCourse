#IDENTITY OPERATOR
#IS operator
a=[3,4,5,7]
b=a
result=a is b
answer1=a is not b
print("the output of ",a,"is",b,":",result)
print("the output of ",a,"is not",b,":",answer1)
#IS not operator
c=[0,9,8,7,6]
d=[0,9,8,7,6]
result1=c is d
answer=c is not d
print("the output of ",c,"is",d,":",result1)
print("the output of ",c,"is not",d,":",answer)