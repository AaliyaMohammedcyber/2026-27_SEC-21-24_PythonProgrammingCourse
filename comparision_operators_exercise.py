# Python Comparison Operators Exercise
a = 10
b = 20
# Equal to
print("result of ",a," == ",b,":", a == b) 
# Not equal to
print("result of ",a," != ",b,":", a != b)  
# Greater than
print("result of ",a," > ",b,":", a > b)   
# Less than
print("result of ",a," < ",b,":", a < b)   
# Greater than or equal to
print("result of ",a," >= ",b,":", a >= b) 
# Less than or equal to
print("result of ",a," <= ",b,":", a <= b)