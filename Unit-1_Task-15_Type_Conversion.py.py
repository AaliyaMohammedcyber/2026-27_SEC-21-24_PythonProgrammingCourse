
#TYPE CONVERSIONS
#INTEGER TO FLOAT
int_num=25
float_num=float(int_num)
print(float_num)
print(type(float_num))
#INTEGER TO STRING
int_num=56
str_num=str(int_num)
print(str_num)
print(type(str_num))
#float to integer
float_num=25
int_num=int(float_num)
print(int_num)
print(type(int_num))
